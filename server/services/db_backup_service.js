import crypto from 'crypto';
import db from '../db.js';

/**
 * Database Backup & Restore Service
 * Produces structured, checksummed database snapshots preserving all
 * relational links, event settings, and 128-D face embeddings.
 * Strictly excludes temporary guest biometric and session records.
 */

/**
 * Computes SHA-256 hash of serialized JSON data.
 * @param {object} obj
 * @returns {string}
 */
export function computeBackupChecksum(dataObj) {
  const serialized = JSON.stringify(dataObj);
  return crypto.createHash('sha256').update(serialized).digest('hex');
}

/**
 * Exports a complete database backup.
 * @param {object} [customDb] - Optional database instance (for testing)
 * @returns {BackupBundle}
 */
export function exportDatabaseBackup(customDb = null) {
  const activeDb = customDb || db;

  // Helper to safely select from table if exists
  const safeSelect = (tableName) => {
    try {
      const tableCheck = activeDb.prepare("SELECT name FROM sqlite_master WHERE type='table' AND name = ?").get(tableName);
      if (!tableCheck) return [];
      return activeDb.prepare(`SELECT * FROM ${tableName}`).all();
    } catch {
      return [];
    }
  };

  // Extract relational datasets
  const photographer = safeSelect('photographer');
  const events = safeSelect('events');
  const folders = safeSelect('folders');
  const media = safeSelect('media');
  const faceEmbeddings = safeSelect('face_embeddings');
  const systemSettings = safeSelect('system_settings');
  const featureFlags = safeSelect('feature_flags');
  const adminUsers = safeSelect('admin_users');
  const adminAuditLogs = safeSelect('admin_audit_logs');
  const platformIncidents = safeSelect('platform_incidents');
  const supportTickets = safeSelect('support_tickets');
  const selectionCollections = safeSelect('selection_collections');
  const selectionItems = safeSelect('selection_items');

  // EXCLUSIONS: guest_sessions, temporary queue states, scratch tables are deliberately omitted per security rules.

  const dataPayload = {
    photographer,
    events,
    folders,
    media,
    face_embeddings: faceEmbeddings,
    system_settings: systemSettings,
    feature_flags: featureFlags,
    admin_users: adminUsers,
    admin_audit_logs: adminAuditLogs,
    platform_incidents: platformIncidents,
    support_tickets: supportTickets,
    selection_collections: selectionCollections,
    selection_items: selectionItems,
  };

  const checksum = computeBackupChecksum(dataPayload);

  return {
    version: '1.0.0',
    type: 'studio_lumina_relational_backup',
    timestamp: new Date().toISOString(),
    sha256: checksum,
    recordCounts: {
      photographer: photographer.length,
      events: events.length,
      folders: folders.length,
      media: media.length,
      face_embeddings: faceEmbeddings.length,
      system_settings: systemSettings.length,
      feature_flags: featureFlags.length,
      admin_users: adminUsers.length,
      admin_audit_logs: adminAuditLogs.length,
      platform_incidents: platformIncidents.length,
      support_tickets: supportTickets.length,
      selection_collections: selectionCollections.length,
      selection_items: selectionItems.length,
    },
    data: dataPayload,
  };
}

/**
 * Restores the database from a backup bundle with strict integrity validation.
 * @param {object} backupBundle - Backup bundle generated by exportDatabaseBackup
 * @param {object} [customDb] - Optional database instance
 * @returns {RestoreReport}
 */
export function restoreDatabaseFromBackup(backupBundle, customDb = null) {
  const activeDb = customDb || db;
  const startTime = Date.now();

  if (!backupBundle || typeof backupBundle !== 'object') {
    throw new Error('Invalid backup bundle: Object expected');
  }

  if (backupBundle.version !== '1.0.0' || !backupBundle.data) {
    throw new Error(`Unsupported backup bundle version: ${backupBundle?.version}`);
  }

  // Verify SHA-256 checksum if present
  if (backupBundle.sha256) {
    const computed = computeBackupChecksum(backupBundle.data);
    if (computed !== backupBundle.sha256) {
      throw new Error('Backup integrity error: SHA-256 checksum mismatch (corrupted backup file)');
    }
  }

  const { data } = backupBundle;

  // Helper to safely execute query if table exists
  const hasTable = (tableName) => {
    try {
      return Boolean(activeDb.prepare("SELECT name FROM sqlite_master WHERE type='table' AND name = ?").get(tableName));
    } catch {
      return false;
    }
  };

  // Execute restore inside transaction
  const runTransaction = () => {
    // 1. Clear leaf-to-root tables in FK dependency order
    const tablesToClean = [
      'selection_items',
      'selection_collections',
      'support_tickets',
      'platform_incidents',
      'admin_audit_logs',
      'admin_users',
      'feature_flags',
      'face_embeddings',
      'media',
      'folders',
      'events',
      'photographer',
      'system_settings',
    ];

    for (const tbl of tablesToClean) {
      if (hasTable(tbl)) {
        activeDb.exec(`DELETE FROM ${tbl};`);
      }
    }

    // 2. Restore photographer
    if (hasTable('photographer') && data.photographer && data.photographer.length > 0) {
      const insertPhotographer = activeDb.prepare(`
        INSERT INTO photographer (id, email, password_hash, business_name, tagline, bio, website, instagram, avatar_url, created_at)
        VALUES (@id, @email, @password_hash, @business_name, @tagline, @bio, @website, @instagram, @avatar_url, @created_at)
      `);
      for (const row of data.photographer) {
        insertPhotographer.run(row);
      }
    }

    // 3. Restore events
    if (hasTable('events') && data.events && data.events.length > 0) {
      const eventCols = [
        'id', 'slug', 'name', 'client_name', 'client_email', 'event_date',
        'location', 'description', 'cover_photo_id', 'status', 'visibility',
        'public_start', 'public_until', 'pin_enabled', 'pin_hash',
        'allow_downloads', 'watermark_enabled', 'watermark_text',
        'face_search_enabled', 'deleted_at', 'purge_after', 'created_at', 'updated_at'
      ];
      const placeholders = eventCols.map((c) => `@${c}`).join(', ');
      const insertEvent = activeDb.prepare(`
        INSERT INTO events (${eventCols.join(', ')})
        VALUES (${placeholders})
      `);
      for (const row of data.events) {
        const item = {};
        for (const col of eventCols) {
          item[col] = row[col] !== undefined ? row[col] : null;
        }
        insertEvent.run(item);
      }
    }

    // 4. Restore folders
    if (hasTable('folders') && data.folders && data.folders.length > 0) {
      const insertFolder = activeDb.prepare(`
        INSERT INTO folders (id, event_id, name, sort_order, created_at)
        VALUES (@id, @event_id, @name, @sort_order, @created_at)
      `);
      for (const row of data.folders) {
        insertFolder.run(row);
      }
    }

    // 5. Restore media
    if (hasTable('media') && data.media && data.media.length > 0) {
      const mediaCols = [
        'id', 'event_id', 'folder_id', 'type', 'filename', 'original_name',
        'mime_type', 'file_size', 'width', 'height', 'storage_key_original',
        'storage_key_preview', 'storage_key_thumbnail', 'video_duration',
        'camera_make', 'camera_model', 'focal_length', 'aperture',
        'shutter_speed', 'iso', 'date_taken', 'status', 'faces_detected', 'created_at'
      ];
      const placeholders = mediaCols.map((c) => `@${c}`).join(', ');
      const insertMedia = activeDb.prepare(`
        INSERT INTO media (${mediaCols.join(', ')})
        VALUES (${placeholders})
      `);
      for (const row of data.media) {
        const item = {};
        for (const col of mediaCols) {
          item[col] = row[col] !== undefined ? row[col] : null;
        }
        insertMedia.run(item);
      }
    }

    // 6. Restore face embeddings
    if (hasTable('face_embeddings') && data.face_embeddings && data.face_embeddings.length > 0) {
      const insertEmbedding = activeDb.prepare(`
        INSERT INTO face_embeddings (id, event_id, photo_id, face_index, box_x, box_y, box_w, box_h, confidence, embedding, created_at)
        VALUES (@id, @event_id, @photo_id, @face_index, @box_x, @box_y, @box_w, @box_h, @confidence, @embedding, @created_at)
      `);
      for (const row of data.face_embeddings) {
        insertEmbedding.run(row);
      }
    }

    // 7. Restore system settings
    if (hasTable('system_settings') && data.system_settings && data.system_settings.length > 0) {
      const insertSetting = activeDb.prepare(`
        INSERT INTO system_settings (key, value, updated_at)
        VALUES (@key, @value, @updated_at)
      `);
      for (const row of data.system_settings) {
        insertSetting.run(row);
      }
    }

    // 8. Restore feature flags
    if (hasTable('feature_flags') && data.feature_flags && data.feature_flags.length > 0) {
      const insertFlag = activeDb.prepare(`
        INSERT INTO feature_flags (key, enabled, description, updated_by, updated_at)
        VALUES (@key, @enabled, @description, @updated_by, @updated_at)
      `);
      for (const row of data.feature_flags) {
        insertFlag.run(row);
      }
    }

    // 9. Restore admin users
    if (hasTable('admin_users') && data.admin_users && data.admin_users.length > 0) {
      const insertAdmin = activeDb.prepare(`
        INSERT INTO admin_users (id, email, password_hash, name, role, status, last_login_at, created_at)
        VALUES (@id, @email, @password_hash, @name, @role, @status, @last_login_at, @created_at)
      `);
      for (const row of data.admin_users) {
        insertAdmin.run(row);
      }
    }

    // 10. Restore admin audit logs
    if (hasTable('admin_audit_logs') && data.admin_audit_logs && data.admin_audit_logs.length > 0) {
      const insertAudit = activeDb.prepare(`
        INSERT INTO admin_audit_logs (id, admin_id, admin_email, action, target_type, target_id, previous_state, new_state, reason, ip_address, request_id, created_at)
        VALUES (@id, @admin_id, @admin_email, @action, @target_type, @target_id, @previous_state, @new_state, @reason, @ip_address, @request_id, @created_at)
      `);
      for (const row of data.admin_audit_logs) {
        insertAudit.run(row);
      }
    }

    // 11. Restore platform incidents
    if (hasTable('platform_incidents') && data.platform_incidents && data.platform_incidents.length > 0) {
      const insertIncident = activeDb.prepare(`
        INSERT INTO platform_incidents (id, title, severity, status, affected_subsystem, description, mitigation_steps, detected_at, mitigated_at, resolved_at, created_by, updated_at)
        VALUES (@id, @title, @severity, @status, @affected_subsystem, @description, @mitigation_steps, @detected_at, @mitigated_at, @resolved_at, @created_by, @updated_at)
      `);
      for (const row of data.platform_incidents) {
        insertIncident.run(row);
      }
    }

    // 12. Restore support tickets
    if (hasTable('support_tickets') && data.support_tickets && data.support_tickets.length > 0) {
      const insertTicket = activeDb.prepare(`
        INSERT INTO support_tickets (id, photographer_id, photographer_email, subject, category, priority, status, assigned_admin_id, notes, created_at, updated_at)
        VALUES (@id, @photographer_id, @photographer_email, @subject, @category, @priority, @status, @assigned_admin_id, @notes, @created_at, @updated_at)
      `);
      for (const row of data.support_tickets) {
        insertTicket.run(row);
      }
    }

    // 13. Restore selection collections
    if (hasTable('selection_collections') && data.selection_collections && data.selection_collections.length > 0) {
      const selCols = [
        'id', 'event_id', 'session_id', 'client_name', 'client_email', 'status',
        'package_name', 'quota', 'min_quota', 'allow_extra', 'selected_count',
        'favorites_count', 'version', 'client_notes', 'photographer_feedback',
        'submitted_at', 'approved_at', 'deadline', 'delivery_status', 'delivery_link',
        'delivery_prepared_at', 'delivery_accessed_at', 'created_at', 'updated_at'
      ];
      const placeholders = selCols.map((c) => `@${c}`).join(', ');
      const insertSel = activeDb.prepare(`
        INSERT INTO selection_collections (${selCols.join(', ')})
        VALUES (${placeholders})
      `);
      for (const row of data.selection_collections) {
        const item = {};
        for (const col of selCols) {
          item[col] = row[col] !== undefined ? row[col] : null;
        }
        insertSel.run(item);
      }
    }

    // 14. Restore selection items
    if (hasTable('selection_items') && data.selection_items && data.selection_items.length > 0) {
      const insertItem = activeDb.prepare(`
        INSERT INTO selection_items (id, selection_id, photo_id, is_favorite, is_selected, notes, created_at, updated_at)
        VALUES (@id, @selection_id, @photo_id, @is_favorite, @is_selected, @notes, @created_at, @updated_at)
      `);
      for (const row of data.selection_items) {
        insertItem.run(row);
      }
    }
  };

  if (activeDb.transaction) {
    activeDb.transaction(runTransaction)();
  } else {
    runTransaction();
  }

  // Post-restore relational integrity verification
  const countTable = (tbl) => {
    if (!hasTable(tbl)) return 0;
    return activeDb.prepare(`SELECT COUNT(*) as count FROM ${tbl}`).get().count;
  };

  const restoredCounts = {
    photographer: countTable('photographer'),
    events: countTable('events'),
    folders: countTable('folders'),
    media: countTable('media'),
    face_embeddings: countTable('face_embeddings'),
    system_settings: countTable('system_settings'),
    feature_flags: countTable('feature_flags'),
    admin_users: countTable('admin_users'),
    admin_audit_logs: countTable('admin_audit_logs'),
    platform_incidents: countTable('platform_incidents'),
    support_tickets: countTable('support_tickets'),
    selection_collections: countTable('selection_collections'),
    selection_items: countTable('selection_items'),
  };

  // Check for broken foreign keys
  const orphanMedia = hasTable('media') && hasTable('events')
    ? activeDb.prepare(`SELECT COUNT(*) as count FROM media WHERE event_id NOT IN (SELECT id FROM events)`).get().count
    : 0;

  const orphanFaces = hasTable('face_embeddings') && hasTable('media')
    ? activeDb.prepare(`SELECT COUNT(*) as count FROM face_embeddings WHERE photo_id NOT IN (SELECT id FROM media)`).get().count
    : 0;

  if (orphanMedia > 0 || orphanFaces > 0) {
    throw new Error(`Relational integrity failure: ${orphanMedia} orphan media and ${orphanFaces} orphan face records found after restore.`);
  }

  return {
    success: true,
    restoredAt: new Date().toISOString(),
    durationMs: Date.now() - startTime,
    restoredCounts,
    integrityCheck: {
      orphanMedia,
      orphanFaces,
      status: 'VERIFIED',
    },
  };
}

export default {
  exportDatabaseBackup,
  restoreDatabaseFromBackup,
  computeBackupChecksum,
};
